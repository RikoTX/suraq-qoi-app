/** «ИИ вернул ошибку (500). Попробуйте позже.» и подобные — с числом внутри. */
export function teacherPatternKk(message: string) {
  const ai = /^ИИ вернул ошибку \((\d+)\)\. Попробуйте позже\.$/.exec(message)
  if (ai) return `ЖИ қате қайтарды (${ai[1]}). Кейінірек қайталаңыз.`
  const count = /^Количество: от 1 до (\d+)$/.exec(message)
  return count ? `Саны: 1-ден ${count[1]}-ке дейін` : null
}
